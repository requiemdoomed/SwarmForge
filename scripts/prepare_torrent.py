"""Split any file into SwarmForge pieces and print the environment to launch a swarm.

Example:
  python3 scripts/prepare_torrent.py ./video.mp4 --pieces-dir ./video_pieces --piece-size 262144
  # Copy the printed export commands into the terminals running tracker.py/node.py.
"""
import argparse
import hashlib
import os
import shlex
from pathlib import Path


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def prepare(source: Path, pieces_dir: Path, piece_size: int):
    source = source.expanduser().resolve()
    pieces_dir = pieces_dir.expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f"Input file does not exist: {source}")
    if piece_size < 1:
        raise ValueError("--piece-size must be positive")
    pieces_dir.mkdir(parents=True, exist_ok=True)
    # Remove only pieces generated by this tool, not arbitrary files in the folder.
    for old in pieces_dir.glob("swarmforge_piece_*.bin"):
        old.unlink()

    names = []
    entries = []
    with source.open("rb") as stream:
        index = 0
        while True:
            data = stream.read(piece_size)
            if not data and index > 0:
                break
            name = f"swarmforge_piece_{index:05d}.bin"
            path = pieces_dir / name
            path.write_bytes(data)
            digest = hashlib.sha256(data).hexdigest()
            names.append(name)
            entries.append((name, len(data), digest))
            index += 1
            if not data:
                break

    torrent_id = hashlib.sha256((source.name + "\0" + "\0".join(e[2] for e in entries)).encode()).hexdigest()[:24]
    return source, pieces_dir, names, entries, torrent_id


def main():
    parser = argparse.ArgumentParser(description="Prepare an arbitrary file for SwarmForge distribution")
    parser.add_argument("file", type=Path, help="file to split into verified pieces")
    parser.add_argument("--pieces-dir", type=Path, default=Path("swarmforge_pieces"), help="output directory for pieces")
    parser.add_argument("--piece-size", type=int, default=256 * 1024, help="piece size in bytes (default: 262144)")
    args = parser.parse_args()
    try:
        source, pieces_dir, names, entries, torrent_id = prepare(args.file, args.pieces_dir, args.piece_size)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))

    print("SwarmForge file preparation complete")
    print(f"Author: Swayam Shakya")
    print(f"Source: {source}")
    print(f"Pieces: {len(names)}")
    print(f"Total bytes: {sum(entry[1] for entry in entries)}")
    print(f"Torrent ID: {torrent_id}")
    print("\n# Set these in every tracker/node terminal before launching SwarmForge:")
    print(f"export SWARMFORGE_TORRENT_ID={shlex.quote('sf-' + torrent_id)}")
    print(f"export SWARMFORGE_PIECE_FILES={shlex.quote(','.join(names))}")
    print(f"export SWARMFORGE_OUTPUT_FILENAME={shlex.quote(source.name)}")
    print(f"export SWARMFORGE_CHUNK_SIZE=65536")
    print(f"# Start the tracker from the project folder: python3 tracker.py")
    print(f"# Start a seed: python3 node.py 5000 --share-dir {shlex.quote(str(pieces_dir))} --output-dir ./downloads/5000")
    print("\nPiece manifest (name | bytes | SHA-256):")
    for name, size, digest in entries:
        print(f"{name} | {size} | {digest}")


if __name__ == "__main__":
    main()
